// LEVERAGE SIMULATOR
// Capital vs Gross Exposure vs Margin Requirements vs Market Movement
// ============================================================================
function initLeverageSimulator() {
  const capitalSlider = document.getElementById("sim-capital");
  const leverageSlider = document.getElementById("sim-leverage");
  const dropSlider = document.getElementById("sim-drop");

  const capitalValEl = document.getElementById("readout-capital");
  const leverageValEl = document.getElementById("readout-leverage");
  const dropValEl = document.getElementById("readout-drop");

  const exposureValEl = document.getElementById("val-exposure");
  const borrowedValEl = document.getElementById("val-borrowed");
  const lossValEl = document.getElementById("val-loss");
  const remainingCapitalEl = document.getElementById("val-remaining-equity");
  const marginBanner = document.getElementById("margin-status-indicator");
  const stackCapitalBar = document.getElementById("stack-bar-capital");
  const phaseButtons = document.querySelectorAll(".phase-nav-btn");

  const phasePresets = {
    capital: { capital: 36, leverage: 1, drop: 0 },
    exposure: { capital: 20, leverage: 5, drop: 0 },
    leverage: { capital: 15, leverage: 7, drop: 0 },
    margin: { capital: 10, leverage: 5, drop: -12 },
    liquidation: { capital: 10, leverage: 5, drop: -27 }
  };

  function updateMath() {
    const capital = parseFloat(capitalSlider.value); // in Billions
    const leverage = parseFloat(leverageSlider.value); // e.g. 5x
    const dropPercent = parseFloat(dropSlider.value); // e.g. -20%

    const totalExposure = capital * leverage;
    const borrowedAmount = totalExposure - capital;
    const marketChangeRatio = dropPercent / 100;
    const dollarChange = totalExposure * marketChangeRatio; // negative for drop
    const remainingEquity = capital + dollarChange;

    capitalValEl.textContent = `$${capital.toFixed(1)}B`;
    leverageValEl.textContent = `${leverage.toFixed(1)}x`;
    dropValEl.textContent = `${dropPercent > 0 ? "+" : ""}${dropPercent}%`;

    exposureValEl.textContent = `$${totalExposure.toFixed(1)}B`;
    borrowedValEl.textContent = `$${borrowedAmount.toFixed(1)}B`;

    if (dollarChange < 0) {
      lossValEl.textContent = `-$${Math.abs(dollarChange).toFixed(1)}B`;
      lossValEl.className = "sim-metric-value danger tnum";
    } else if (dollarChange > 0) {
      lossValEl.textContent = `+$${dollarChange.toFixed(1)}B`;
      lossValEl.className = "sim-metric-value gold tnum";
    } else {
      lossValEl.textContent = "$0.0B";
      lossValEl.className = "sim-metric-value tnum";
    }

    remainingCapitalEl.textContent = remainingEquity > 0 ? `$${remainingEquity.toFixed(1)}B` : "$0.0B (DEFICIT)";

    // Update Stack Bar Percentage
    const equityPct = Math.min(100, Math.max(2, (1 / leverage) * 100));
    stackCapitalBar.style.width = `${equityPct}%`;
    stackCapitalBar.textContent = `Equity: ${equityPct.toFixed(0)}%`;

    // Check Margin Call status
    if (remainingEquity <= 0) {
      marginBanner.className = "margin-status-banner danger";
      marginBanner.innerHTML = `<span><strong>MARGIN CALL DEFAULT:</strong> 100% of equity wiped out. Lender unsecured shortfall of -$${Math.abs(remainingEquity).toFixed(1)}B.</span>`;
      remainingCapitalEl.className = "sim-metric-value danger tnum";
    } else if (remainingEquity < capital * 0.35) {
      marginBanner.className = "margin-status-banner danger";
      marginBanner.innerHTML = `<span><strong>VARIATION MARGIN TRIGGERED:</strong> Collateral depleted by ${(100 - (remainingEquity/capital)*100).toFixed(0)}%. Banks issuing emergency calls.</span>`;
      remainingCapitalEl.className = "sim-metric-value danger tnum";
    } else {
      marginBanner.className = "margin-status-banner safe";
      marginBanner.innerHTML = `<span><strong>MARGIN RATIO ADEQUATE:</strong> Equity cushion covers current swap variance.</span>`;
      remainingCapitalEl.className = "sim-metric-value gold tnum";
    }
  }

  // Wire phase buttons
  phaseButtons.forEach((btn) => {
    btn.addEventListener("click", () => {
      const phase = btn.getAttribute("data-phase");
      const preset = phasePresets[phase];
      if (!preset) return;

      phaseButtons.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");

      capitalSlider.value = preset.capital;
      leverageSlider.value = preset.leverage;
      dropSlider.value = preset.drop;

      updateMath();
    });
  });

  [capitalSlider, leverageSlider, dropSlider].forEach((sl) => {
    if (sl) {
      sl.addEventListener("input", () => {
        // Clear active state if custom moved
        phaseButtons.forEach((b) => b.classList.remove("active"));
        updateMath();
      });
    }
  });

  updateMath();
}

