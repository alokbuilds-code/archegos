// THE DOCUMENT ROOM / ARCHIVE DOSSIER
// ============================================================================
function initDocumentRoom() {
  const docListEl = document.getElementById("doc-room-list");
  const docTitleEl = document.getElementById("doc-active-title");
  const docMetaEl = document.getElementById("doc-active-meta");
  const docStampEl = document.getElementById("doc-active-stamp");
  const docSheetEl = document.getElementById("doc-paper-content");
  const docPageIndicator = document.getElementById("doc-page-indicator");
  const prevBtn = document.getElementById("doc-prev-page");
  const nextBtn = document.getElementById("doc-next-page");
  const openSourceBtn = document.getElementById("doc-open-source");

  // Modal inspection elements
  const fullscreenBtn = document.getElementById("doc-fullscreen-btn");
  const modalOverlay = document.getElementById("doc-modal-overlay");
  const modalTitle = document.getElementById("modal-doc-title");
  const modalStamp = document.getElementById("modal-doc-stamp");
  const modalSheetText = document.getElementById("modal-sheet-text");
  const modalPageCount = document.getElementById("modal-page-count");
  const modalZoomIn = document.getElementById("modal-zoom-in");
  const modalZoomOut = document.getElementById("modal-zoom-out");
  const modalPrevPage = document.getElementById("modal-prev-page");
  const modalNextPage = document.getElementById("modal-next-page");
  const modalExternalLink = document.getElementById("modal-external-link");
  const modalCloseBtn = document.getElementById("modal-close-btn");
  const modalSheet = document.getElementById("modal-sheet");

  let currentDocIndex = 0;
  let currentPageIndex = 0;
  let currentZoom = 1.0;

  function updateModalSheet() {
    const doc = documentRoomData[currentDocIndex];
    if (!doc || !modalOverlay) return;

    if (modalTitle) modalTitle.textContent = doc.title;
    if (modalStamp) modalStamp.textContent = doc.stamp;
    if (modalSheetText) modalSheetText.textContent = doc.pages[currentPageIndex] || doc.pages[0];
    if (modalPageCount) modalPageCount.textContent = `Page ${currentPageIndex + 1} of ${doc.pages.length}`;
    if (modalExternalLink) modalExternalLink.href = doc.sourceUrl;
    if (modalPrevPage) modalPrevPage.disabled = currentPageIndex === 0;
    if (modalNextPage) modalNextPage.disabled = currentPageIndex >= doc.pages.length - 1;
  }

  function renderDocument(docIndex, pageIndex) {
    const doc = documentRoomData[docIndex];
    if (!doc) return;

    currentDocIndex = docIndex;
    currentPageIndex = pageIndex;

    docTitleEl.textContent = doc.title;
    docMetaEl.textContent = `${doc.institution} — ${doc.date}`;
    docStampEl.textContent = doc.stamp;
    docSheetEl.textContent = doc.pages[pageIndex] || doc.pages[0];
    docPageIndicator.textContent = `Page ${pageIndex + 1} of ${doc.pages.length}`;
    openSourceBtn.href = doc.sourceUrl;

    prevBtn.disabled = pageIndex === 0;
    nextBtn.disabled = pageIndex >= doc.pages.length - 1;

    // Update list buttons active state
    document.querySelectorAll(".doc-item-btn").forEach((btn, idx) => {
      btn.classList.toggle("active", idx === docIndex);
    });

    updateModalSheet();
  }

  function openModal() {
    if (!modalOverlay) return;
    currentZoom = 1.0;
    if (modalSheet) modalSheet.style.transform = "scale(1.0)";
    updateModalSheet();
    modalOverlay.classList.add("open");
    document.body.style.overflow = "hidden";
  }

  function closeModal() {
    if (!modalOverlay) return;
    modalOverlay.classList.remove("open");
    document.body.style.overflow = "auto";
  }

  // Populate sidebar
  if (docListEl) {
    docListEl.innerHTML = "";
    documentRoomData.forEach((doc, idx) => {
      const li = document.createElement("li");
      li.innerHTML = `
        <button class="doc-item-btn ${idx === 0 ? 'active' : ''}">
          <span class="doc-btn-title">${doc.title}</span>
          <span class="doc-btn-meta">
            <span>${doc.date}</span>
            <span>${doc.type.split(" ")[0]}</span>
          </span>
        </button>
      `;
      li.querySelector("button").addEventListener("click", () => renderDocument(idx, 0));
      docListEl.appendChild(li);
    });
  }

  if (prevBtn) {
    prevBtn.addEventListener("click", () => {
      if (currentPageIndex > 0) renderDocument(currentDocIndex, currentPageIndex - 1);
    });
  }

  if (nextBtn) {
    nextBtn.addEventListener("click", () => {
      const maxPages = documentRoomData[currentDocIndex].pages.length;
      if (currentPageIndex < maxPages - 1) renderDocument(currentDocIndex, currentPageIndex + 1);
    });
  }

  // Modal inspection listeners
  if (fullscreenBtn) fullscreenBtn.addEventListener("click", openModal);
  if (modalCloseBtn) modalCloseBtn.addEventListener("click", closeModal);

  if (modalOverlay) {
    modalOverlay.addEventListener("click", (e) => {
      if (e.target === modalOverlay || e.target.classList.contains("doc-modal-body")) {
        closeModal();
      }
    });
  }

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && modalOverlay && modalOverlay.classList.contains("open")) {
      closeModal();
    }
  });

  if (modalZoomIn) {
    modalZoomIn.addEventListener("click", () => {
      currentZoom = Math.min(1.5, currentZoom + 0.1);
      if (modalSheet) modalSheet.style.transform = `scale(${currentZoom})`;
    });
  }

  if (modalZoomOut) {
    modalZoomOut.addEventListener("click", () => {
      currentZoom = Math.max(0.75, currentZoom - 0.1);
      if (modalSheet) modalSheet.style.transform = `scale(${currentZoom})`;
    });
  }

  if (modalPrevPage) {
    modalPrevPage.addEventListener("click", () => {
      if (currentPageIndex > 0) renderDocument(currentDocIndex, currentPageIndex - 1);
    });
  }

  if (modalNextPage) {
    modalNextPage.addEventListener("click", () => {
      const maxPages = documentRoomData[currentDocIndex].pages.length;
      if (currentPageIndex < maxPages - 1) renderDocument(currentDocIndex, currentPageIndex + 1);
    });
  }

  renderDocument(0, 0);
}

