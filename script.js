function initScrollTriggers() {
  if (typeof gsap === "undefined" || typeof ScrollTrigger === "undefined") return;

  gsap.registerPlugin(ScrollTrigger);

  // Restrained section header reveals
  gsap.utils.toArray(".section-header-block").forEach((header) => {
    gsap.from(header, {
      scrollTrigger: {
        trigger: header,
        start: "top 85%",
        toggleActions: "play none none reverse"
      },
      opacity: 0,
      y: 20,
      duration: 1,
      ease: "power2.out"
    });
  });

  // Stagger reveal on position cards
  gsap.from(".position-card", {
    scrollTrigger: {
      trigger: ".positions-grid",
      start: "top 80%"
    },
    opacity: 0,
    y: 25,
    stagger: 0.12,
    duration: 0.8,
    ease: "power2.out"
  });

  // Chronicle cards reveal
  gsap.utils.toArray(".chronicle-card").forEach((card) => {
    gsap.from(card, {
      scrollTrigger: {
        trigger: card,
        start: "top 85%"
      },
      opacity: 0,
      x: -15,
      duration: 0.9,
      ease: "power2.out"
    });
  });
}

