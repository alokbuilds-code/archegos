function initImageResilience() {
  document.querySelectorAll("img").forEach((img) => {
    img.addEventListener("error", () => {
      // Do not replace with random stock image. Replace with institutional typographic placeholder.
      const fallbackBox = document.createElement("div");
      fallbackBox.style.padding = "1rem";
      fallbackBox.style.backgroundColor = "var(--bg-surface)";
      fallbackBox.style.border = "1px solid var(--border-dim)";
      fallbackBox.style.fontFamily = "var(--font-mono)";
      fallbackBox.style.fontSize = "0.72rem";
      fallbackBox.style.color = "var(--text-accent)";
      fallbackBox.style.textAlign = "center";
      fallbackBox.textContent = `[ARCHIVAL ASSET: ${img.alt || "DOCUMENTED REFERENCE"}]`;
      if (img.parentElement) {
        img.parentElement.replaceChild(fallbackBox, img);
      }
    });
  });
}

