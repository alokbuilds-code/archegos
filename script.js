function initSourceArchive() {
  const searchInput = document.getElementById("archive-search-input");
  const gridEl = document.getElementById("archive-grid");
  const countEl = document.getElementById("archive-match-count");
  if (!gridEl) return;

  function renderCitations(query = "") {
    gridEl.innerHTML = "";
    const q = query.toLowerCase().trim();

    const filtered = sourceArchiveData.filter((item) => {
      return (
        item.title.toLowerCase().includes(q) ||
        item.publisher.toLowerCase().includes(q) ||
        (item.author && item.author.toLowerCase().includes(q)) ||
        item.date.toLowerCase().includes(q)
      );
    });

    if (countEl) countEl.textContent = `${filtered.length} of ${sourceArchiveData.length} Sources Displayed`;

    filtered.forEach((c) => {
      const card = document.createElement("div");
      card.className = "citation-card";
      card.innerHTML = `
        <div class="citation-num tnum">[${c.id}]</div>
        <div class="citation-title">${c.title}</div>
        <div class="citation-publisher">${c.author ? `${c.author} — ` : ''}${c.publisher} (${c.date})</div>
        <a href="${c.url}" target="_blank" rel="noopener noreferrer" class="citation-external-link">
          <span>Open Verified Source</span>
        </a>
      `;
      gridEl.appendChild(card);
    });
  }

  if (searchInput) {
    searchInput.addEventListener("input", (e) => renderCitations(e.target.value));
  }

  renderCitations();
}

