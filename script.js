function initTimeline() {
  const streamEl = document.getElementById("timeline-stream");
  const scrubberNav = document.getElementById("timeline-scrubber");
  if (!streamEl) return;

  function renderMilestones(filterYear = "ALL") {
    streamEl.innerHTML = "";
    const filtered = filterYear === "ALL" 
      ? timelineData 
      : timelineData.filter((m) => m.year === filterYear);

    filtered.forEach((item) => {
      const card = document.createElement("div");
      card.className = "timeline-milestone-card";
      card.innerHTML = `
        <div class="milestone-date-col">
          <div class="milestone-year tnum">${item.year}</div>
          <div class="milestone-date-detail">${item.date}</div>
        </div>
        <div>
          <h4 class="milestone-title">${item.title}</h4>
          <p class="milestone-desc">${item.desc}</p>
          <div class="milestone-source-ref">Source: ${item.source}</div>
        </div>
      `;
      streamEl.appendChild(card);
    });
  }

  // Populate scrubber buttons
  if (scrubberNav) {
    const years = ["ALL", "2012", "2013", "2014", "2020", "2021", "2022", "2023", "2024"];
    scrubberNav.innerHTML = "";
    years.forEach((yr) => {
      const btn = document.createElement("button");
      btn.className = `timeline-year-btn ${yr === "ALL" ? "active" : ""}`;
      btn.textContent = yr;
      btn.addEventListener("click", () => {
        document.querySelectorAll(".timeline-year-btn").forEach((b) => b.classList.remove("active"));
        btn.classList.add("active");
        renderMilestones(yr);
      });
      scrubberNav.appendChild(btn);
    });
  }

  renderMilestones("ALL");
}

