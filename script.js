// CUSTOM EDITORIAL CURSOR (Subtle Dot & Gold Tracking Ring)
// ============================================================================
function initCustomCursor() {
  const dot = document.getElementById("custom-cursor-dot");
  const ring = document.getElementById("custom-cursor-ring");
  if (!dot || !ring) return;

  // Disable on coarse pointer / touch devices
  if (window.matchMedia("(pointer: coarse)").matches) return;

  let mouseX = -100;
  let mouseY = -100;
  let ringX = -100;
  let ringY = -100;

  window.addEventListener("mousemove", (e) => {
    mouseX = e.clientX;
    mouseY = e.clientY;
    dot.style.transform = `translate(${mouseX}px, ${mouseY}px)`;
  });

  function renderRing() {
    ringX += (mouseX - ringX) * 0.18;
    ringY += (mouseY - ringY) * 0.18;
    ring.style.transform = `translate(${ringX}px, ${ringY}px)`;
    requestAnimationFrame(renderRing);
  }
  requestAnimationFrame(renderRing);

  // Expand ring over interactive elements
  const hoverSelectors = "a, button, input[type='range'], input[type='text'], .position-card, .metric-card, .phase-nav-btn, .trs-step-btn, .timeline-year-btn, .doc-item-btn, .doc-action-btn";
  document.addEventListener("mouseover", (e) => {
    if (e.target.closest(hoverSelectors)) {
      ring.classList.add("active");
    }
  });

  document.addEventListener("mouseout", (e) => {
    if (e.target.closest(hoverSelectors)) {
      ring.classList.remove("active");
    }
  });

  // Fade out cursor when leaving browser viewport
  document.documentElement.addEventListener("mouseleave", () => {
    dot.style.opacity = "0";
    ring.style.opacity = "0";
  });

  document.documentElement.addEventListener("mouseenter", () => {
    dot.style.opacity = "1";
    ring.style.opacity = "1";
  });
}

